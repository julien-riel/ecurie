"""Adaptateur `mlx-flashhead` : une tête entière générée sur la parole reçue.

Le portage MLX d'AI2Apps fournit le pipeline complet : une image carrée et une
parole à 16 kHz en entrée, un MP4 en sortie. Il est vendoré sous
`runtimes/mlx-flashhead/vendor/` et appelé sans modification. L'adaptateur fait ce
que le portage ne fait pas.

**Le cadrage.** Le portage prend le carré central de l'image. L'amont propose de
cadrer sur le visage (`--use_face_crop`, MediaPipe, un carré de deux largeurs de
visage, le centre du visage à 55 % de la hauteur). C'est ce cadrage qui est repris
ici, avec Apple Vision à la place de MediaPipe : Vision est dans le système et ne
demande aucun poids. Sur un portrait en pied ou un plan large, le carré central
couperait la tête.

**Le son.** Le portage écrit dans la vidéo la parole qu'il a écoutée, à 16 kHz en
mono. La vidéo est ici remultiplexée avec l'enregistrement d'origine, réencodé en
AAC, sans toucher aux images.

**La panne à craindre est une bouche figée**, qui rend un job vert et une vidéo
fausse. `mouth_motion` la mesure autour des lèvres repérées sur le portrait cadré,
et un avertissement la signale.

**La mémoire ne croît presque pas avec la durée.** Le réseau travaille par tronçons
de 33 images et le portage les écrit au fil de l'eau. Seule la parole est encodée
d'un bloc par wav2vec2, ce qui coûte quelques mégaoctets par minute.
"""

import gc
import io
import os
import subprocess
import sys
import tempfile
import time
from pathlib import Path
from typing import Any

from ecurie_runtime.workers.base import (
    InferRequest,
    InferResult,
    ProgressFn,
    Worker,
    WorkerError,
    main,
    peak_rss_bytes,
)

ENV_NAME = "mlx-flashhead"
REPAIR = f"ecurie env sync {ENV_NAME} && python3 runtimes/{ENV_NAME}/vendorer.py"
VAR_VENDOR = "ECURIE_FLASHHEAD_VENDOR"
VIDEO_NAME = "video.mp4"

FPS = 25
TAILLE = 512
PAS = 4
MAX_SECONDES = 600.0
VARIANTE = "pro"

# Le cadrage de l'amont (`flash_head/utils/facecrop.py`) : un carré de deux largeurs
# de visage, dont le centre du visage occupe 55 % de la hauteur depuis le haut.
RAPPORT_VISAGE = 2.0
PART_AU_DESSUS = 0.55

# Autour des lèvres, en part de leur largeur : la tête bouge d'une image à l'autre,
# et la boîte doit rester sur la bouche.
MARGE_BOUCHE = 0.6
# En deçà, sur 255, la bouche générée est tenue pour figée.
MOUVEMENT_MINIMAL = 0.5
# Sous ce niveau, le signal ne contient pas de parole audible.
SILENCE_RMS = 1e-3

MENTION = "Synthetic talking head: generated by SoulX-FlashHead Pro"

Boite = tuple[int, int, int, int]
Point = tuple[float, float]


# --- ce qui se calcule sans les poids ----------------------------------------


def carre_autour_du_visage(visage: Boite, largeur: int, hauteur: int) -> Boite:
    """Le carré de l'amont autour d'un visage, gardé entier dans l'image.

    L'amont rogne le carré sur les bords, ce qui donne un rectangle que le pipeline
    recadre ensuite au centre : la tête n'y est plus où l'amont l'avait placée. Ici,
    le carré est décalé pour rester dans l'image, et réduit seulement si l'image
    est plus étroite que lui.
    """
    x1, y1, x2, y2 = visage
    if x2 <= x1 or y2 <= y1:
        raise ValueError("boîte de visage dégénérée")
    côté = min(int(round((x2 - x1) * RAPPORT_VISAGE)), largeur, hauteur)
    cx, cy = (x1 + x2) / 2, (y1 + y2) / 2
    gauche = int(round(cx - côté / 2))
    haut = int(round(cy - côté * PART_AU_DESSUS))
    gauche = min(max(0, gauche), largeur - côté)
    haut = min(max(0, haut), hauteur - côté)
    return gauche, haut, gauche + côté, haut + côté


def carre_central(largeur: int, hauteur: int) -> Boite:
    """Le plus grand carré centré : ce que le portage prend sans cadrage."""
    côté = min(largeur, hauteur)
    gauche, haut = (largeur - côté) // 2, (hauteur - côté) // 2
    return gauche, haut, gauche + côté, haut + côté


def boite_bouche(lèvres: list[Point], taille: int) -> Boite:
    """Une boîte autour des lèvres, élargie pour suivre la tête qui bouge."""
    xs = [p[0] for p in lèvres]
    ys = [p[1] for p in lèvres]
    marge = (max(xs) - min(xs)) * MARGE_BOUCHE
    if marge <= 0:
        raise ValueError("contour des lèvres dégénéré")
    return (
        max(0, int(min(xs) - marge)),
        max(0, int(min(ys) - marge)),
        min(taille, int(max(xs) + marge) + 1),
        min(taille, int(max(ys) + marge) + 1),
    )


def bas_du_carre(taille: int) -> Boite:
    """Repli quand Vision ne trouve pas les lèvres : le tiers central du bas."""
    return taille // 3, taille // 2, 2 * taille // 3, 5 * taille // 6


def commande_remux(
    ffmpeg: str, video: Path, audio: Path, secondes: float, sortie: Path
) -> list[str]:
    """Les images du portage telles quelles, le son d'origine réencodé en AAC."""
    return [
        ffmpeg, "-y", "-v", "error",
        "-i", str(video), "-t", f"{secondes:.3f}", "-i", str(audio),
        "-map", "0:v:0", "-map", "1:a:0",
        "-c:v", "copy", "-c:a", "aac", "-b:a", "192k", "-shortest",
        "-map_metadata", "-1", "-metadata", f"comment={MENTION}",
        "-fflags", "+bitexact", "-flags:a", "+bitexact",
        "-movflags", "+faststart",
        str(sortie),
    ]  # fmt: skip


def candidats_vendor(depuis: Path, courant: Path, depuis_env: str | None = None) -> list[Path]:
    """Où chercher le code vendoré : la variable, puis en remontant vers `runtimes/`."""
    if depuis_env:
        return [Path(depuis_env).expanduser()]
    trouvés = [
        parent / "runtimes" / ENV_NAME / "vendor"
        for parent in (depuis.resolve(), *depuis.resolve().parents)
        if (parent / "runtimes" / ENV_NAME).is_dir()
    ]
    return trouvés + [courant / "runtimes" / ENV_NAME / "vendor"]


def vendor_dir() -> Path:
    candidats = candidats_vendor(Path(__file__), Path.cwd(), os.environ.get(VAR_VENDOR))
    for candidat in candidats:
        if (candidat / "flashhead_mlx" / "pipeline.py").is_file():
            return candidat
    cherchés = "\n      ".join(str(c) for c in candidats)
    raise WorkerError(
        f"portage FlashHead absent. Cherché dans :\n      {cherchés}\n\n"
        f"Le poser avec :\n\n    {REPAIR}\n\n"
        f"Un dossier rangé autrement se déclare par {VAR_VENDOR}."
    )


def _import_runtime() -> tuple[Any, ...]:
    vendor = vendor_dir()
    if str(vendor) not in sys.path:
        sys.path.insert(0, str(vendor))
    try:
        import imageio_ffmpeg
        import mlx.core as mx
        import numpy as np
        from flashhead_mlx.pipeline import FlashHeadPipeline
    except ImportError as exc:
        raise WorkerError(
            f"runtime {ENV_NAME} indisponible dans cet environnement ({exc}) — "
            f"le reconstruire avec `{REPAIR}`"
        ) from exc
    return mx, np, imageio_ffmpeg, FlashHeadPipeline


def detecter_visages(image: Any) -> list[tuple[Boite, list[Point] | None, float]]:
    """Boîte, lèvres et aire de chaque visage, en pixels, origine en haut à gauche."""
    import Foundation
    import Vision

    largeur, hauteur = image.size
    tampon = io.BytesIO()
    image.save(tampon, format="PNG")
    octets = tampon.getvalue()
    données = Foundation.NSData.dataWithBytes_length_(octets, len(octets))
    gestionnaire = Vision.VNImageRequestHandler.alloc().initWithData_options_(données, {})
    requête = Vision.VNDetectFaceLandmarksRequest.alloc().init()
    réussi, erreur = gestionnaire.performRequests_error_([requête], None)
    if not réussi:
        raise WorkerError(f"Apple Vision a échoué sur l'image : {erreur}")

    visages = []
    for résultat in requête.results() or []:
        b = résultat.boundingBox()
        x1 = b.origin.x * largeur
        x2 = (b.origin.x + b.size.width) * largeur
        y1 = (1 - b.origin.y - b.size.height) * hauteur
        y2 = (1 - b.origin.y) * hauteur
        boite = (int(x1), int(y1), int(round(x2)), int(round(y2)))
        lèvres = None
        repères = résultat.landmarks()
        région = repères.outerLips() if repères else None
        if région is not None:
            n = région.pointCount()
            points = région.pointsInImageOfSize_((largeur, hauteur)).as_tuple(n)
            lèvres = [(float(p.x), float(hauteur - p.y)) for p in points]
        visages.append((boite, lèvres, float(b.size.width * b.size.height)))
    return visages


# --- l'adaptateur ------------------------------------------------------------


class FlashHeadWorker(Worker):
    """Portrait et parole → tête parlante, par SoulX-FlashHead Pro sur MLX."""

    name = "flashhead"

    def __init__(self) -> None:
        super().__init__()
        self.mx: Any = None
        self.np: Any = None
        self.ffmpeg: str = ""
        self.pipe: Any = None
        self.defaults: dict[str, Any] = {}
        self._peak_load = 0

    def load(self, variant: dict[str, Any]) -> dict[str, Any]:
        mx, np, imageio_ffmpeg, pipeline = _import_runtime()
        self.mx, self.np = mx, np
        self.ffmpeg = imageio_ffmpeg.get_ffmpeg_exe()
        self.defaults = dict(variant.get("defaults") or {})

        brut = str(variant.get("weights_path") or "").strip()
        ref = variant.get("ref") or "<ref>"
        racine = Path(brut) if brut else None
        if racine is None or not (racine / "Model_Pro").is_dir():
            raise WorkerError(
                f"poids absents : {brut or '(chemin vide)'} ne contient pas Model_Pro/ — "
                f"télécharger avec : ecurie pull {ref}"
            )
        try:
            self.pipe = pipeline(racine, racine / "wav2vec2", variant=VARIANTE)
        except Exception as exc:  # noqa: BLE001 — remonte avec la réparation
            raise WorkerError(f"chargement impossible : {type(exc).__name__}: {exc}") from exc
        self._peak_load = self._pic() or 0
        return {"versions": self._versions()}

    def infer(self, request: InferRequest, progress: ProgressFn) -> InferResult:
        if self.pipe is None:
            raise WorkerError("infer avant load — aucun modèle en mémoire")
        mx = self.mx
        avertissements: list[str] = []

        portrait = self._fichier(request, "portrait")
        audio = self._fichier(request, "audio")
        max_seconds = float(self._reglage(request, "max_seconds", MAX_SECONDES))
        if not 1 <= max_seconds <= MAX_SECONDES:
            raise WorkerError(f"max_seconds={max_seconds:g} hors de 1 à {MAX_SECONDES:g}")
        seed = int(self._reglage(request, "seed", 0))
        if seed < 0:
            raise WorkerError(f"seed={seed} : une graine est un entier positif")

        mx.reset_peak_memory()
        début = time.monotonic()

        with tempfile.TemporaryDirectory(dir=request.output_dir) as brut:
            dossier = Path(brut)
            progress(5, "cadrage du portrait")
            cadré, carré, détecté, bouche = self._cadrer(portrait, dossier, avertissements)

            progress(10, "écoute de la parole")
            wav, secondes = self._ecouter(audio, dossier, max_seconds, avertissements)

            def suivre(courant: int, total: int) -> None:
                progress(15 + int(75 * courant / max(1, total)), f"pas {courant}/{total}")

            brute = dossier / "brute.mp4"
            try:
                self.pipe.generate(
                    cadré, wav, brute, size=TAILLE, seed=seed, steps=PAS, progress=suivre
                )
            except Exception as exc:  # noqa: BLE001 — l'erreur du portage, lisible
                raise WorkerError(f"génération échouée : {type(exc).__name__}: {exc}") from exc

            progress(92, "son d'origine")
            sortie = request.output_dir / VIDEO_NAME
            remux = subprocess.run(
                commande_remux(self.ffmpeg, brute, audio, secondes, sortie),
                capture_output=True,
                check=False,
            )
            if remux.returncode != 0:
                raise WorkerError(
                    f"écriture de la vidéo impossible : "
                    f"{remux.stderr.decode(errors='replace')[-500:]}"
                )
        calcul = time.monotonic() - début

        progress(96, "sonde de la bouche")
        images, mouvement = self._sonder(sortie, bouche)
        if mouvement < MOUVEMENT_MINIMAL:
            avertissements.append(
                f"bouche presque figée (mouth_motion={mouvement:.2f} sur 255) : vérifier que "
                "l'enregistrement contient de la parole et que le visage est bien cadré."
            )

        return InferResult(
            output={
                "video": VIDEO_NAME,
                "fps": FPS,
                "width": TAILLE,
                "height": TAILLE,
                "frames": images,
                "duration_seconds": round(images / FPS, 3),
                "crop_box": list(carré),
                "face_detected": détecté,
                "mouth_motion": round(mouvement, 3),
            },
            metrics={
                "rtf": round(calcul / max(secondes, 1e-6), 5),
                "infer_ms": int(calcul * 1000),
                "avertissements": avertissements,
                "peak_memory_bytes": self.peak_memory_bytes(),
            },
        )

    def unload(self) -> None:
        self.pipe = None
        self._peak_load = 0
        gc.collect()
        if self.mx is not None:
            self.mx.clear_cache()

    def peak_memory_bytes(self) -> int | None:
        """Le pic de MLX, chargement compris ; le RSS en plancher."""
        pic = self._pic()
        rss = peak_rss_bytes()
        if pic is None:
            return rss
        return max(pic, self._peak_load, rss or 0)

    # --- détails -------------------------------------------------------------

    def _cadrer(
        self, chemin: Path, dossier: Path, avertissements: list[str]
    ) -> tuple[Path, Boite, bool, Boite]:
        """Le carré à faire parler, écrit en PNG, et la boîte de la bouche dans ce carré."""
        from PIL import Image, ImageOps

        try:
            image = ImageOps.exif_transpose(Image.open(chemin)).convert("RGB")
        except Exception as exc:  # noqa: BLE001 — PIL lève des types variés
            raise WorkerError(f"portrait illisible : {chemin} ({exc})") from exc
        largeur, hauteur = image.size

        visages = detecter_visages(image)
        if visages:
            if len(visages) > 1:
                avertissements.append("plusieurs visages : seul le plus grand est cadré.")
            boite = max(visages, key=lambda v: v[2])[0]
            try:
                carré = carre_autour_du_visage(boite, largeur, hauteur)
            except ValueError as exc:
                raise WorkerError(f"visage inexploitable : {exc}") from exc
            détecté = True
        else:
            carré = carre_central(largeur, hauteur)
            détecté = False
            avertissements.append(
                "aucun visage détecté par Apple Vision : le carré central du portrait a "
                "été pris, et la tête peut y être coupée."
            )

        côté = carré[2] - carré[0]
        if côté < TAILLE:
            avertissements.append(
                f"carré de {côté} pixels agrandi à {TAILLE} : le visage sera moins net."
            )
        cadré = image.crop(carré).resize((TAILLE, TAILLE), Image.Resampling.LANCZOS)
        cible = dossier / "portrait.png"
        cadré.save(cible)

        # Les lèvres sont cherchées sur le carré tel que le réseau le voit.
        bouche = bas_du_carre(TAILLE)
        dans_le_carré = detecter_visages(cadré)
        lèvres = max(dans_le_carré, key=lambda v: v[2])[1] if dans_le_carré else None
        if lèvres:
            try:
                bouche = boite_bouche(lèvres, TAILLE)
            except ValueError:
                pass
        return cible, carré, détecté, bouche

    def _ecouter(
        self, audio: Path, dossier: Path, max_seconds: float, avertissements: list[str]
    ) -> tuple[Path, float]:
        """La parole à 16 kHz en mono, tronquée, et sa durée."""
        np = self.np
        import soundfile

        wav = dossier / "ecoute.wav"
        lecture = subprocess.run(
            [self.ffmpeg, "-y", "-v", "error", "-i", str(audio), "-map", "0:a:0",
             "-ac", "1", "-ar", "16000", "-c:a", "pcm_s16le", str(wav)],
            capture_output=True,
            check=False,
        )  # fmt: skip
        if lecture.returncode != 0:
            raise WorkerError(
                f"parole illisible : {audio} ({lecture.stderr.decode(errors='replace')[-300:]})"
            )
        signal, frequence = soundfile.read(wav, dtype="float32")
        entier = signal.shape[0] / frequence
        if entier > max_seconds:
            signal = signal[: int(max_seconds * frequence)]
            soundfile.write(wav, signal, frequence, subtype="PCM_16")
            avertissements.append(f"parole tronquée à {max_seconds:g} s sur {entier:.1f} s.")
        if signal.shape[0] < frequence / FPS:
            raise WorkerError(f"parole trop courte pour une image à {FPS} im/s : {audio}")
        if float(np.sqrt(np.mean(signal**2))) < SILENCE_RMS:
            avertissements.append("enregistrement silencieux : la bouche restera fermée.")
        return wav, signal.shape[0] / frequence

    def _sonder(self, video: Path, bouche: Boite) -> tuple[int, float]:
        """Nombre d'images de la vidéo écrite, et écart moyen autour de la bouche."""
        import av

        np = self.np
        x1, y1, x2, y2 = bouche
        précédente = None
        cumul = 0.0
        comparaisons = 0
        images = 0
        with av.open(str(video)) as conteneur:
            for image in conteneur.decode(video=0):
                zone = image.to_ndarray(format="gray")[y1:y2, x1:x2].astype(np.float32)
                if précédente is not None:
                    cumul += float(np.mean(np.abs(zone - précédente)))
                    comparaisons += 1
                précédente = zone
                images += 1
        if images == 0:
            raise WorkerError(f"aucune image dans la vidéo écrite : {video}")
        return images, (cumul / comparaisons if comparaisons else 0.0)

    def _fichier(self, request: InferRequest, champ: str) -> Path:
        brut = request.get(champ)
        if not brut:
            raise WorkerError(f"« {champ} » est obligatoire pour talking-head")
        chemin = Path(str(brut))
        if not chemin.is_absolute():
            chemin = request.output_dir / chemin
        if not chemin.is_file():
            raise WorkerError(f"{champ} introuvable : {chemin}")
        return chemin

    def _reglage(self, request: InferRequest, nom: str, defaut: Any) -> Any:
        valeur = request.get(nom)
        if valeur is not None:
            return valeur
        if self.defaults.get(nom) is not None:
            return self.defaults[nom]
        return defaut

    def _pic(self) -> int | None:
        if self.mx is None:
            return None
        try:
            return int(self.mx.get_peak_memory())
        except Exception:  # noqa: BLE001 — une mesure ratée ne fait pas échouer un job
            return None

    def _versions(self) -> dict[str, str]:
        versions = {}
        for nom, module in (("mlx", "mlx.core"), ("av", "av")):
            try:
                importé = __import__(module, fromlist=["__version__"])
                versions[nom] = str(getattr(importé, "__version__", "?"))
            except ImportError:
                pass
        return versions


if __name__ == "__main__":
    raise SystemExit(main(FlashHeadWorker))
